import type { CompanyRow } from '@/shared/api/generated/types.gen';
import { dateLabel, metric } from '@/shared/lib/format';
import type { SortKey } from './params';

/** 0-100 points (score, coverage or a sector percentile, 100 = best) as a 0..1 colour position. */
export const score = (value: number | null | undefined) => (value == null ? null : value / 100);

export type RankingColumn = {
  key: string;
  label: string;
  /** Backend order key; the backend sorts the whole filtered universe. */
  sort: SortKey;
  /** Backend columns written to the CSV for this column. */
  exportAs: string[];
  /** Always shown; not offered in the column picker. */
  fixed?: boolean;
  /** Also shown on phones. */
  mobile?: boolean;
  value: (row: CompanyRow) => string;
  position?: (row: CompanyRow) => number | null;
  scope?: string;
};

const plain = (key: string, label: string, compact = false): RankingColumn => ({
  key,
  label,
  sort: key as SortKey,
  exportAs: [key],
  value: (row) => metric(row.metrics[key], compact),
});

const block = (key: string, label: string): RankingColumn => ({
  ...plain(key, label),
  position: (row) => score(row.metrics[key]?.value),
  scope: 'del universo',
});

function earnings(row: CompanyRow): string {
  const next = row.next_earnings;
  if (!next) return '—';
  return dateLabel(next.event_date) + (next.is_estimate ? ' (estimada)' : '');
}

