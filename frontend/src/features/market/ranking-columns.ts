export const DEFAULT_COLUMNS = ['price', 'confidence', 'market_cap', 'pe'];
const OPTIONAL = new Set(RANKING_COLUMNS.filter((column) => !column.fixed).map((c) => c.key));

export function visibleColumns(chosen: string[]): RankingColumn[] {
  return RANKING_COLUMNS.filter((column) => column.fixed || chosen.includes(column.key));
}

export type RankingPreferences = { columns: string[]; query: string };

const STORAGE_KEY = 'gabi.ranking.preferences.v1';
// Filters, order and rows are kept; the page and the experimental weights are not.
const KEPT = new Set([
  'search',
  'sectors',
  'exclude_sectors',
  'min_market_cap',
  'golden_cross_only',
  'hide_no_data',
  'earnings',
  'earnings_days',
  'order_by',
  'direction',
  'limit',
]);

/** Saved local preferences; anything unreadable or unknown is dropped, never trusted. */
export function loadPreferences(): RankingPreferences {
  try {
    const raw: unknown = JSON.parse(localStorage.getItem(STORAGE_KEY) ?? 'null');
    if (!raw || typeof raw !== 'object') return { columns: DEFAULT_COLUMNS, query: '' };
    const { columns, query } = raw as Partial<RankingPreferences>;
    return {
      columns: Array.isArray(columns)
        ? columns.filter((key) => typeof key === 'string' && OPTIONAL.has(key))
        : DEFAULT_COLUMNS,
      query: typeof query === 'string' ? keptQuery(new URLSearchParams(query)) : '',
    };
  } catch {
    return { columns: DEFAULT_COLUMNS, query: '' };
  }
}

export function keptQuery(params: URLSearchParams): string {
  const kept = new URLSearchParams();
  params.forEach((value, key) => {
    if (KEPT.has(key)) kept.append(key, value.slice(0, 200));
  });
  return kept.toString();
}

export function savePreferences(preferences: RankingPreferences): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(preferences));
  } catch {
    // Private mode or full storage: the page keeps working without remembering.
  }
}

/** CSV of the filtered view with the visible columns, generated by the backend. */
export function exportHref(params: URLSearchParams, columns: RankingColumn[]): string {
  // The same query as the table (experimental weights included), every row instead of one page.
  const query = new URLSearchParams(params);
  ['offset', 'limit', 'columns'].forEach((key) => query.delete(key));
  columns.flatMap((column) => column.exportAs).forEach((key) => query.append('columns', key));
  return '/api/v1/ranking/export.csv?' + query.toString();
}
